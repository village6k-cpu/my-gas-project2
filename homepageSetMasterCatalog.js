function homepageSetMasterAliases_() {
  var aliases = homepageSetMasterProducts_().filter(function(row) {
    return row[2] && row[1] !== row[2];
  }).map(function(row) {
    return { alias: row[1], canonicalName: row[2] };
  });
  // 같은 모델에서 구수가 확인된 경우만 연결한다. SE와 C1 Pro는 서로 다른 모델이다.
  [4, 6].forEach(function(count) {
    ['홀리랜드 솔리드컴', '솔리드컴'].forEach(function(brand) {
      ['C1 Pro', 'C1프로'].forEach(function(model) {
        [count + '구', count + 'S', count + '인용'].forEach(function(size) {
          aliases.push({ alias: [brand, model, size].join(' '), canonicalName: '홀리랜드 솔리드컴 ' + count + 'S' });
        });
      });
    });
  });
  ['캐논 R6 Mark 2 + 100-400', '캐논 R6 Mark II + 100-400', '캐논 R6 Mark 2 + EF 100-400mm II'].forEach(function(name) {
    aliases.push({ alias: name, canonicalName: '캐논 R6 Mark 2 + EF 100-400mm II (EF-EOS R 어댑터 포함)' });
  });
  return aliases;
}

